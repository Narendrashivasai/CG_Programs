package com.codegnan.oppexamples;

public class Car {
	private String model;
    private int year;
	public String getName() {
		return model;
	}
	public void setModel(String name) {
		this.model = name;
	}
	public int getYear() {
		return year;
	}
	public void setYear(int year) {
		this.year = year;
	}
}
